/**
 * Pre-compiled word boundary regex entries sorted by pattern length descending
 * to ensure compound multi-word phrases match before individual sub-words.
 */
export const COMPILED_PRONUNCIATION_ENTRIES: PronunciationEntry[] = Object.entries(
  PRONUNCIATION_MAP
)
  .sort(([a], [b]) => b.length - a.length)
  .map(([term, spoken]) => {
    const escaped = term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const startsWithWord = /^\w/.test(term);
    const endsWithWord = /\w$/.test(term);
    const patternStr = `${startsWithWord ? '\\b' : ''}${escaped}${endsWithWord ? '\\b' : ''}`;
    return {
      pattern: new RegExp(patternStr, 'g'),
      spoken,
    };
  });
